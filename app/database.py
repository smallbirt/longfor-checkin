SCHEDULER_LOCK = 1279673163


class Session:
    def __init__(self, connection, postgres=False, schema=None):
        self.connection, self.postgres, self.schema = connection, postgres, schema

    def execute(self, statement, params=()):
        if self.postgres:
            # All SQL comes from application constants. User input is bound separately.
            statement = statement.replace('?', '%s')
        return self.connection.execute(statement, params)

    def executescript(self, script):
        if self.postgres:
            script = script.replace('INTEGER PRIMARY KEY AUTOINCREMENT',
                                    'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            for statement in script.split(';'):
                if statement.strip():
                    self.connection.execute(statement)
        else:
            self.connection.executescript(script)

    def insert(self, statement, params):
        if self.postgres:
            return self.execute(statement + ' RETURNING id', params).fetchone()['id']
        return self.execute(statement, params).lastrowid

    def serialize(self, label):
        if self.postgres:
            self.execute('SELECT pg_advisory_xact_lock(hashtext(?))', (self.schema + ':' + label,))
        else:
            self.execute('BEGIN IMMEDIATE')

    def reset_sequence(self, table):
        if self.postgres:
            from psycopg import sql
            # Identifier composition is only used for validated application table names.
            if table not in ('users', 'jobs', 'outbox', 'wecom_outbox', 'mini_push_subscriptions', 'mini_push_outbox'):
                raise ValueError('无效的序列表。')
            self.connection.execute(sql.SQL('SELECT setval(pg_get_serial_sequence(%s, %s), '
                'COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM {}').format(sql.Identifier(table)),
                (self.schema + '.' + table, 'id'))


class PostgreSQL:
    def __init__(self, url):
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool
        size = int(os.environ.get('PG_POOL_MAX', '5'))
        if not 1 <= size <= 10:
            raise ValueError('PG_POOL_MAX 需为 1–10。')
        self.url = url
        self.pool = ConnectionPool(url, min_size=0, max_size=size, timeout=10, open=True,
            kwargs={'row_factory': dict_row, 'connect_timeout': 5,
                    'application_name': 'longfor_checkin',
                    'options': '-c statement_timeout=20000 -c lock_timeout=10000 -c idle_in_transaction_session_timeout=30000'})
        atexit.register(self.close)
        try:
            with self.pool.connection() as conn:
                name = conn.execute('SELECT current_database() AS name').fetchone()['name']
                if name in ('hr', 'postgres', 'template0', 'template1'):
                    raise ValueError('请连接签到专用数据库，不能使用 HR 库或 PostgreSQL 系统库。')
        except Exception:
            self.close()
            raise

    @contextmanager
    def connect(self, schema):
        with self.pool.connection() as conn:
            conn.execute("SELECT set_config('search_path', %s, true)", ('"' + schema + '", pg_catalog',))
            yield Session(conn, True, schema)

    def acquire_scheduler(self):
        import psycopg
        self.lease = psycopg.connect(self.url, autocommit=True, connect_timeout=5,
                                    application_name='longfor_checkin_scheduler',
                                    options='-c statement_timeout=5000', keepalives_idle=10,
                                    keepalives_interval=5, keepalives_count=3, tcp_user_timeout=15000)
        if not self.lease.execute('SELECT pg_try_advisory_lock(%s)', (SCHEDULER_LOCK,)).fetchone()[0]:
            self.lease.close()
            raise RuntimeError('签到数据库已有调度器运行，不能启动第二个实例。')

    def check_scheduler(self):
        self.lease.execute('SELECT 1')

    def close(self):
        if getattr(self, 'lease', None):
            self.lease.close()
        self.pool.close()
